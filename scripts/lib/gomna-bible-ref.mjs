function normalizeBookToken(raw) {
  let s = String(raw || '')
    .normalize('NFKC')
    .trim()
    .replace(/\./g, '')
    .replace(/\s+/g, ' ');
  // Roman / fullwidth ordinals → arabic prefix glued without space for alias keys
  s = s
    .replace(/^Ⅱ\s*/u, '2')
    .replace(/^Ⅰ\s*/u, '1')
    .replace(/^Ⅲ\s*/u, '3')
    .replace(/^II\s+/i, '2')
    .replace(/^I\s+/i, '1')
    .replace(/^III\s+/i, '3')
    .replace(/^2\s+/, '2')
    .replace(/^1\s+/, '1')
    .replace(/^3\s+/, '3');
  s = s.replace(/\s+/g, '');
  return s.toLowerCase();
}

export function getKoreanBookName(bookId) {
  return KO_BOOK_BY_ID[String(bookId || '').trim()] || null;
}

export function resolveBookToken(token) {
  const key = normalizeBookToken(token);
  if (!key) return null;
  if (BOOK_ALIASES[key]) return BOOK_ALIASES[key];
  // try original NFKC without lowercasing for CJK-only maps stored lowercase via NFKC
  const rawKey = String(token || '')
    .normalize('NFKC')
    .trim()
    .replace(/\s+/g, '');
  if (BOOK_ALIASES[rawKey]) return BOOK_ALIASES[rawKey];
  const lowerRaw = rawKey.toLowerCase();
  if (BOOK_ALIASES[lowerRaw]) return BOOK_ALIASES[lowerRaw];
  return null;
}

/**
 * Parse a single reference display string into a structured ref.
 * Ranges keep verseEnd; navigation should use verseStart.
 */
export function parseBibleReference(input) {
  const display = String(input || '').trim();
  if (!display) {
    return { ok: false, reason: 'empty', display };
  }

  // "Book chapter:verse" or "Book chapter:start-end" (allow CJK book tokens)
  let match = display.match(
    /^(.+?)\s*(\d+)\s*[:：]\s*(\d+)(?:\s*[-–—〜~]\s*(\d+))?$/u,
  );
  if (match) {
    const bookId = resolveBookToken(match[1]);
    if (!bookId) {
      return { ok: false, reason: 'unknown_book', display, bookToken: match[1] };
    }
    const chapter = Number(match[2]);
    const verseStart = Number(match[3]);
    const verseEnd = match[4] ? Number(match[4]) : verseStart;
    if (!Number.isInteger(chapter) || chapter < 1) {
      return { ok: false, reason: 'bad_chapter', display };
    }
    if (!Number.isInteger(verseStart) || verseStart < 1) {
      return { ok: false, reason: 'bad_verse', display };
    }
    return {
      ok: true,
      bookId,
      koBookName: getKoreanBookName(bookId),
      chapter,
      verse: verseStart,
      verseStart,
      verseEnd: Number.isInteger(verseEnd) && verseEnd >= verseStart ? verseEnd : verseStart,
      rangeText:
        match[4] && Number(match[4]) !== verseStart
          ? `${verseStart}-${match[4]}`
          : String(verseStart),
      display,
    };
  }

  // "Book chapter장/편"
  match = display.match(/^(.+?)\s*(\d+)\s*(장|편)$/u);
  if (match) {
    const bookId = resolveBookToken(match[1]);
    if (!bookId) {
      return { ok: false, reason: 'unknown_book', display, bookToken: match[1] };
    }
    const chapter = Number(match[2]);
    return {
      ok: true,
      bookId,
      koBookName: getKoreanBookName(bookId),
      chapter,
      verse: 1,
      verseStart: 1,
      verseEnd: null,
      rangeText: null,
      wholeChapter: true,
      display,
    };
  }

  return { ok: false, reason: 'bad_format', display };
}

export function parseBibleReferenceList(input) {
  const raw = String(input || '').trim();
  if (!raw) return [];
  return raw
    .split(/[,，、;；]/u)
    .map((part) => parseBibleReference(part.trim()))
    .filter((item) => item && item.display);
}

