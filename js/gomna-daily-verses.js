  function pad2(n){return (n<10?'0':'')+n;}
  var DAY_MS=86400000;
  var KST_OFFSET=9*60*60*1000;
  var SCHEDULE_EPOCH=Date.UTC(2026,9,1);
  function kstParts(d){
    var date=d==null?new Date():new Date(d);
    if(!isFinite(date.getTime()))throw new TypeError('Invalid daily verse date');
    var x=new Date(date.getTime()+KST_OFFSET);
    return {y:x.getUTCFullYear(),m:x.getUTCMonth()+1,day:x.getUTCDate()};
  }
  function kstDateKey(d){
    var p=kstParts(d);
    return p.y+'-'+pad2(p.m)+'-'+pad2(p.day);
  }
  function parseDateKey(key){
    var m=String(key||'').match(/^(\d{4})-(\d{2})-(\d{2})$/);
    if(!m)return null;
    var p={y:+m[1],m:+m[2],day:+m[3]}, check=new Date(Date.UTC(p.y,p.m-1,p.day));
    return check.getUTCFullYear()===p.y&&check.getUTCMonth()+1===p.m&&check.getUTCDate()===p.day?p:null;
  }
  function partsForDate(d){
    if(typeof d==='string'&&/^\d{4}-/.test(d)&&d.length===10){
      var parsed=parseDateKey(d);
      if(!parsed)throw new TypeError('Invalid daily verse date key');
      return parsed;
    }
    if(d&&typeof d==='object'&&!(d instanceof Date)&&d.day){
      var today=kstParts();
      var key=(d.y||today.y)+'-'+pad2(d.m||today.m)+'-'+pad2(d.day);
      var parts=parseDateKey(key);
      if(!parts)throw new TypeError('Invalid daily verse date parts');
      return parts;
    }
    return kstParts(d);
  }
